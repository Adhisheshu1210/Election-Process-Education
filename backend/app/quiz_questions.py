def get_random_questions(mode="practice", count=20):
    """Get random questions for practice or exam mode"""
    import random
    questions = QUIZ_QUESTIONS.copy()
    random.shuffle(questions)
    return questions[:count]

def get_question_by_id(q_id):
    """Get a specific question by ID"""
    for q in QUIZ_QUESTIONS:
        if q["id"] == q_id:
            return q
    return None

def get_questions_by_topic(topic):
    """Get all questions for a specific topic"""
    return [q for q in QUIZ_QUESTIONS if q["topic"] == topic]

def get_all_topics():
    """Get list of all quiz topics"""
    topics = set()
    for q in QUIZ_QUESTIONS:
        topics.add(q["topic"])
    return sorted(list(topics))
